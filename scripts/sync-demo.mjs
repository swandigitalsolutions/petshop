// Copies the in-browser demo backend and demo data into each frontend app.
// Each Vercel service builds from its own folder, so the apps can't import files
// from outside it. Run `npm run sync:demo` after editing shared/demo or the seed data.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const backend = fs.readFileSync(path.join(root, 'shared/demo/backend.js'), 'utf8')
  .replace("from '../../server/src/seed/data.js'", "from './data.js'");
const data = fs.readFileSync(path.join(root, 'server/src/seed/data.js'), 'utf8');
const banner = '// GENERATED by scripts/sync-demo.mjs. Edit shared/demo/backend.js or server/src/seed/data.js instead.\n';
for (const app of ['client', 'admin']) {
  const dir = path.join(root, app, 'src', 'demo');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'backend.js'), banner + backend);
  fs.writeFileSync(path.join(dir, 'data.js'), banner + data);
}
console.log('demo backend synced into client/src/demo and admin/src/demo');
